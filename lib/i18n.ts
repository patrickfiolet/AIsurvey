/** Detect language from country code */
export function detectLanguageFromCountry(country: string): string {
  const countryLanguageMap: Record<string, string> = {
    NL: 'nl', BE: 'nl', SR: 'nl',
    DE: 'de', AT: 'de', CH: 'de', LI: 'de', LU: 'de',
    US: 'en', GB: 'en', AU: 'en', CA: 'en', NZ: 'en', IE: 'en', ZA: 'en', IN: 'en',
    FR: 'fr', MC: 'fr', SN: 'fr',
    ES: 'es', MX: 'es', AR: 'es', CO: 'es', CL: 'es', PE: 'es', VE: 'es',
    PT: 'pt', BR: 'pt', AO: 'pt', MZ: 'pt',
    IT: 'it', SM: 'it', VA: 'it',
  }
  return countryLanguageMap[country?.toUpperCase()] || 'nl'
}

/** Get translation by dot-notation key */
export function getTranslation(key: string, language: string = 'nl'): string {
  const keys = key.split('.')
  let value: any = translations[language] || translations['nl']

  for (const k of keys) {
    value = value?.[k]
    if (value === undefined) {
      // Fallback to Dutch
      value = translations['nl']
      for (const fk of keys) {
        value = value?.[fk]
        if (value === undefined) return key
      }
      return value
    }
  }

  return typeof value === 'string' ? value : key
}
